import { createClient } from '@supabase/supabase-js'

/*
  What the admin dashboard needs, and nothing else. The two reads here are not plain rows
  of one table: the roster spans community_members and users, and a join code is written to
  community but generated by this area's own rules. Both live here so that community.js and
  community_members.js stay a record of their own tables and this page's logic has one place
  to change. /api/god maps the action 'admin' onto this class and answers it only for an
  admin of the community_id in the request.
*/

/*
  The alphabet a join code is drawn from. No 0, O, 1 or I, so a code read out in a service
  or glanced off a screen cannot be mistyped for its look-alike. 32 characters divide 256
  exactly, so taking the remainder of a random byte does not lean on any of them.
*/
const CODE_CHARS = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'

export function generateJoinId(length = 6) {
  const bytes = new Uint8Array(length)
  crypto.getRandomValues(bytes)

  let code = ''
  for (const byte of bytes) code += CODE_CHARS[byte % CODE_CHARS.length]
  return code
}

export class AdminDashboard {
  constructor(url = process.env.SUPABASE_URL, key = process.env.SUPABASE_ANON_KEY) {
    if (!url || !key) throw new Error('Supabase url and key are required')
    this.client = createClient(url, key)
  }

  #id(community_id) {
    if (!community_id) throw new Error('community_id is required')
  }

  /*
    Everyone in one community, with the name from users beside the role. `users!inner` is
    the join: community_members holds only the email and the role, users holds who that
    address belongs to, and the inner form drops a link whose user row is missing instead
    of returning a row with no name. Flattened here so a page gets one object per person,
    admins first, then leaders, then members.
  */
  async roster(community_id) {
    this.#id(community_id)
    const { data, error } = await this.client
      .from('community_members')
      .select('email, role, users!inner(name, surname)')
      .eq('community_id', community_id)
      .order('role')
      .order('email')
    if (error) throw error
    return data.map(({ email, role, users }) => ({
      email,
      role,
      name: users?.name ?? '',
      surname: users?.surname ?? '',
    }))
  }

  // True when some community already answers to that code.
  async #codeTaken(join_id) {
    const { data, error } = await this.client
      .from('community')
      .select('community_id')
      .eq('join_id', join_id)
      .maybeSingle()
    if (error) throw error
    return Boolean(data)
  }

  // A code nobody holds yet: drawn again for as long as the table already answers to it.
  async #freeCode() {
    for (let attempt = 1; attempt <= 10; attempt += 1) {
      const join_id = generateJoinId()
      if (!(await this.#codeTaken(join_id))) return join_id
    }
    throw new Error('could not draw a free join code, please try again')
  }

  /*
    Replaces this community's join code with a generated one and returns the row, so the
    caller reads the new code off the same answer that wrote it. The code is checked
    against every row before it is written: join_id is unique, so a clash would be refused
    by the database anyway, and drawing again until the code is free is what keeps that
    refusal from ever reaching the person waiting for a code to say aloud.
  */
  async changeCode(community_id) {
    this.#id(community_id)
    const join_id = await this.#freeCode()
    const { data, error } = await this.client
      .from('community')
      .update({ join_id })
      .eq('community_id', community_id)
      .select()
      .maybeSingle()
    if (error) throw error
    if (!data) throw new Error(`no community with id ${community_id}`)
    return data
  }
}
